import { createHash, randomBytes } from "crypto";

// ─────────────────────────────────────────────
//  CONFIG — Edit these values before running
// ─────────────────────────────────────────────
const CONFIG = {
  name: "Vraj Shah",
  email: "vraj@itacon.com",
  phone: "9876543210",          // 10-digit Indian mobile (without +91)
  role: "salesperson",                // "admin" or "salesperson"
  password: "Sales@1234",       // Must have: 8+ chars, uppercase, lowercase, number, special char
};
// ─────────────────────────────────────────────

function generateSalt(length = 16) {
  return randomBytes(length).toString("base64url");
}

function hashPassword(password, salt) {
  return createHash("sha256")
    .update(`${salt}:${password}`)
    .digest("hex");
}

const salt = generateSalt();
const hash = hashPassword(CONFIG.password, salt);

const firestoreDoc = {
  name: CONFIG.name,
  email: CONFIG.email.toLowerCase(),
  phone: CONFIG.phone,
  role: CONFIG.role,
  status: "active",
  passwordHash: hash,
  passwordSalt: salt,
  createdAt: new Date().toISOString(),
};

console.log("\n✅ Staff account details generated successfully!\n");
console.log("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
console.log("  FIRESTORE COLLECTION : users");
console.log("  DOCUMENT ID          : (auto-generated by Firestore)");
console.log("━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
console.log("\n📄 Fields to add in Firestore:\n");
console.log(JSON.stringify(firestoreDoc, null, 2));
console.log("\n━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━");
console.log("\n🔐 Login credentials for the web portal:");
console.log(`  Email    : ${CONFIG.email}`);
